function DataRow({
  label,
  value,
  mono = false,
  highlight = false,
}: {
  label: string;
  value: string;
  mono?: boolean;
  highlight?: boolean;
}) {
  return (
    <div style={drStyles.row}>
      <span style={drStyles.label}>{label}</span>
      <span
        style={{
          ...drStyles.value,
          fontFamily: mono ? "'Source Code Pro', monospace" : "'Rajdhani', sans-serif",
          fontWeight: mono ? 400 : 600,
          color: highlight ? 'var(--gold)' : 'var(--t0)',
        }}
      >
        {value}
      </span>
    </div>
  );
}

